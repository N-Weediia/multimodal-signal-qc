"""Exploratory task-fingerprint similarity analysis for phase 5.

The input is the channel-level fNIRS event-delta source table generated by
``phase5_spatial_visuals.py``.  Each subject/session/task vector is a mean
response across protocol-labeled action blocks; cosine similarity is used only to
describe whether the three action fingerprints are more or less distinct.
Events and channels are not independent observations.
"""
from __future__ import annotations

import csv
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

try:  # Support both ``python scripts/...`` and ``import scripts...``.
    from .paired7_config import PAIRED_SUBJECTS, phase_root
except ImportError:  # pragma: no cover - direct script execution
    from paired7_config import PAIRED_SUBJECTS, phase_root

ROOT = Path(__file__).resolve().parents[1]
OUT = phase_root(5)
TASKS = ["摸头", "摸膝", "摸腰"]
TASK_LABELS = ["head", "knee", "waist"]
PAIRED = list(PAIRED_SUBJECTS)


def _read_vectors(path: Path):
    buckets: dict[tuple[str, str, str], dict[str, float]] = {}
    with path.open(encoding="utf-8-sig", newline="") as handle:
        for row in csv.DictReader(handle):
            if row.get("modality") != "fNIRS" or row.get("feature") != "event_delta":
                continue
            subject, session, task, channel = row.get("subject", ""), row.get("session", ""), row.get("task", ""), row.get("channel", "")
            if subject not in PAIRED or task not in TASKS or session not in {"base_line", "sec_test"}:
                continue
            try:
                value = float(row["value"])
            except (KeyError, TypeError, ValueError):
                continue
            buckets.setdefault((subject, session, task), {})[channel] = value
    vectors = {}
    for key, values in buckets.items():
        channels = sorted(values, key=lambda x: int(x.removeprefix("CH")))
        vectors[key] = np.asarray([values[c] for c in channels], dtype=float)
    return vectors


def _cosine(a: np.ndarray, b: np.ndarray) -> float:
    den = float(np.linalg.norm(a) * np.linalg.norm(b))
    return float(np.dot(a, b) / den) if den > 0 else float("nan")


def main() -> None:
    vectors = _read_vectors(OUT / "figure_spatial_source_data.csv")
    rows: list[dict[str, object]] = []
    matrices: dict[str, list[np.ndarray]] = {"base_line": [], "sec_test": []}
    subject_sep: dict[str, dict[str, float]] = {}
    for subject in PAIRED:
        subject_sep[subject] = {}
        for session in ("base_line", "sec_test"):
            if not all((subject, session, task) in vectors for task in TASKS):
                continue
            matrix = np.eye(len(TASKS), dtype=float)
            for i, task_a in enumerate(TASKS):
                for j, task_b in enumerate(TASKS):
                    matrix[i, j] = _cosine(vectors[(subject, session, task_a)], vectors[(subject, session, task_b)])
            matrices[session].append(matrix)
            offdiag = matrix[np.triu_indices(3, 1)]
            separation = float(np.nanmean(1.0 - offdiag))
            subject_sep[subject][session] = separation
            for i, task_a in enumerate(TASKS):
                for j, task_b in enumerate(TASKS):
                    if i < j:
                        rows.append({"subject": subject, "session": session, "task_a": task_a, "task_b": task_b, "cosine_similarity": float(matrix[i, j]), "task_separation_index": separation, "n_channels": int(vectors[(subject, session, task_a)].size)})
    if not rows:
        raise SystemExit("No paired task vectors found in source data")
    base = np.nanmean(np.stack(matrices["base_line"]), axis=0)
    follow = np.nanmean(np.stack(matrices["sec_test"]), axis=0)
    delta = follow - base
    fig, axes = plt.subplots(1, 4, figsize=(12.5, 3.4), gridspec_kw={"width_ratios": [1, 1, 1, 1.35]})
    vmax = max(float(np.nanmax(np.abs(np.stack([base, follow, delta])))), 1e-6)
    for ax, mat, title, cmap, vmin, vmax_i in ((axes[0], base, "baseline", "viridis", -1, 1), (axes[1], follow, "sec_test", "viridis", -1, 1), (axes[2], delta, "delta", "RdBu_r", -vmax, vmax)):
        im = ax.imshow(mat, cmap=cmap, vmin=vmin, vmax=vmax_i)
        ax.set_xticks(range(3), TASK_LABELS); ax.set_yticks(range(3), TASK_LABELS); ax.set_title(title)
        for i in range(3):
            for j in range(3): ax.text(j, i, f"{mat[i, j]:.2f}", ha="center", va="center", fontsize=8)
        fig.colorbar(im, ax=ax, fraction=.046, pad=.04)
    sep_values = []
    for subject in PAIRED:
        if "base_line" not in subject_sep[subject] or "sec_test" not in subject_sep[subject]:
            continue
        sep_values.append((subject, subject_sep[subject]["base_line"], subject_sep[subject]["sec_test"]))
    ax = axes[3]
    for subject, before, after in sep_values:
        ax.plot([0, 1], [before, after], marker="o", lw=.9, color="#555", alpha=.75)
        ax.text(1.03, after, subject[-4:], fontsize=7, va="center")
    ax.set_xticks([0, 1], ["baseline", "sec_test"]); ax.set_ylabel("mean 1 - cosine similarity")
    ax.set_title("Task separation index\n(higher = more distinct fingerprints)")
    ax.grid(axis="y", alpha=.2)
    fig.suptitle(f"fNIRS task-fingerprint representational similarity (paired n={len(sep_values)})\nCosine similarity of protocol-labeled action fingerprints; descriptive only", y=.995, fontsize=11)
    fig.subplots_adjust(top=.78, wspace=.5)
    for suffix, dpi in (("png", 600), ("svg", None), ("pdf", None)):
        kwargs = {"dpi": dpi} if dpi else {}
        fig.savefig(OUT / f"fnirs_task_fingerprint_rsa.{suffix}", bbox_inches="tight", **kwargs)
    plt.close(fig)
    with (OUT / "fnirs_task_fingerprint_rsa.csv").open("w", encoding="utf-8-sig", newline="") as handle:
        fields = ["subject", "session", "task_a", "task_b", "cosine_similarity", "task_separation_index", "n_channels"]
        writer = csv.DictWriter(handle, fieldnames=fields); writer.writeheader(); writer.writerows(rows)


if __name__ == "__main__":
    main()
